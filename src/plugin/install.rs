/// Copies every bundled plugin to the plugin directory if it doesn't already
/// exist there, or overwrites it if the installed binary differs from the
/// embedded one (e.g. after a mantis upgrade). Syntax definitions go into
/// `{plugin_dir}/syntaxes/`. Also removes any retired shell-script plugins
/// that were superseded by Rust binaries (pre-0.8 upgrade cleanup).
pub(crate) fn install_bundled_plugins() {
    let dir = default_plugin_dir();
    let _ = std::fs::create_dir_all(&dir);

    for (_name, binary_name, data) in BUNDLED_PLUGINS {
        let binary_filename = if cfg!(windows) {
            format!("{binary_name}.exe")
        } else {
            binary_name.to_string()
        };
        let plugin_path = dir.join(&binary_filename);
        if data.is_empty() {
            continue;
        }
        // Bundled plugin names are known ahead of time, so an exact-name
        // match here is treated as one of our own binaries and overwritten
        // on content mismatch, even if a user placed their own file there.
        let up_to_date = std::fs::read(&plugin_path)
            .map(|existing| existing == *data)
            .unwrap_or(false);
        if up_to_date {
            set_executable(&plugin_path);
            continue;
        }
        write_binary_atomically(&dir, &plugin_path, &binary_filename, data);
    }

    let syntax_dir = dir.join("syntaxes");
    let _ = std::fs::create_dir_all(&syntax_dir);
    for (name, content) in BUNDLED_SYNTAX_PLUGINS {
        let path = syntax_dir.join(name);
        let up_to_date = std::fs::read_to_string(&path)
            .map(|existing| existing == *content)
            .unwrap_or(false);
        if !up_to_date {
            write_file_atomically(&syntax_dir, &path, name, content.as_bytes());
        }
    }

    remove_retired_bundled_plugins();
}

fn write_binary_atomically(dir: &Path, plugin_path: &Path, filename: &str, data: &[u8]) {
    let tmp_path = dir.join(format!(".{filename}.tmp.{}", std::process::id()));
    if std::fs::write(&tmp_path, data).is_ok() {
        set_executable(&tmp_path);
        if std::fs::rename(&tmp_path, plugin_path).is_err() {
            let _ = std::fs::remove_file(plugin_path);
            if std::fs::rename(&tmp_path, plugin_path).is_err()
                && std::fs::write(plugin_path, data).is_ok()
            {
                set_executable(plugin_path);
            }
        }
        let _ = std::fs::remove_file(&tmp_path);
    }
}

fn write_file_atomically(dir: &Path, file_path: &Path, filename: &str, data: &[u8]) {
    let tmp_path = dir.join(format!(".{filename}.tmp.{}", std::process::id()));
    if std::fs::write(&tmp_path, data).is_ok() {
        if std::fs::rename(&tmp_path, file_path).is_err() {
            let _ = std::fs::remove_file(file_path);
            let _ = std::fs::rename(&tmp_path, file_path);
        }
        let _ = std::fs::remove_file(&tmp_path);
    }
}

/// Removes retired bundled plugin files from the plugin directory.
///
/// Deletes only exact-name matches that mantis is known to have shipped
/// (see `RETIRED_BUNDLED_PLUGINS`). User-authored plugins are never touched.
/// Errors are silently ignored so a permissions issue does not crash startup.
pub(crate) fn remove_retired_bundled_plugins() {
    let dir = default_plugin_dir();
    for name in RETIRED_BUNDLED_PLUGINS {
        let path = dir.join(name);
        if path.exists() {
            let _ = std::fs::remove_file(&path);
        }
    }
}

/// Returns the list of retired plugin filenames that should be removed
/// from the plugin directory and filtered out of config `[plugins]` entries.
pub(crate) fn retired_bundled_plugins() -> &'static [&'static str] {
    RETIRED_BUNDLED_PLUGINS
}

#[cfg(unix)]
fn set_executable(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    let _ = std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755));
}
#[cfg(not(unix))]
fn set_executable(_path: &Path) {}
