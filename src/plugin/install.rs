//! Plugin installation and default directory discovery.
//!
//! Locates the platform-specific plugin directory, writes out the bundled
//! binary plugins embedded at compile time via atomic file replacement, and
//! installs syntax definitions into `{plugin_dir}/syntaxes/`.
//!
//! Bundled binary plugins (`iconize`, `markdown`, `python`, `rust`, `go`,
//! `json`, `sh`, `yaml`, `terraform`) are embedded at compile time via
//! `build.rs` →
//! `$OUT_DIR/plugin_binaries.rs` — no search-path dance or fallback `cargo
//! build` at runtime. This ensures they are always available for non-source
//! installs (release artifacts, Homebrew, etc.).
//!
//! Bundled syntax plugins (`toml`, `typescript`, `dockerfile`,
//! `nginx`, `justfile`) are embedded via `include_str!` and written to the
//! `syntaxes/` subdirectory on first run. The matching
//! `terraform.sublime-syntax` ships the same way, but it declares its own
//! `file_extensions` (`.tf`, `.tfvars`, `.hcl`) and is auto-discovered from
//! `{plugin_dir}/syntaxes/` rather than being managed by a `[plugins]`
//! entry — the `terraform` plugin itself is a process plugin (language
//! provider, `fold` capability).

include!(concat!(env!("OUT_DIR"), "/plugin_binaries.rs"));

use std::path::{Path, PathBuf};

use crate::plugin::types::{PluginEntry, PluginKind};

/// Returns `(name, PluginEntry)` pairs for every plugin that ships with `mantis`.
///
/// All plugins shipped with `mantis` (markdown, iconize, python, rust, go, json, sh,
/// yaml, k8s, terraform, toml, typescript, dockerfile, nginx, justfile) are enabled by
/// default. User config
/// entries with `or_insert` always win over these defaults, so an explicit
/// `enabled = false` in `mantis.toml` is respected.
pub(crate) fn bundled_plugin_entries() -> Vec<(String, PluginEntry)> {
    let mut entries = Vec::new();
    for (name, binary_name, _data) in BUNDLED_PLUGINS {
        let filename = if cfg!(windows) {
            format!("{binary_name}.exe")
        } else {
            binary_name.to_string()
        };
        // Store the path relative to `default_plugin_dir()` (resolved at spawn
        // time in `PluginManager::activate_all`). An absolute path here would be
        // serialised verbatim into the user's `mantis.toml` on the first plugin
        // toggle, pinning a machine-specific home directory into a config that is
        // meant to be portable.
        let enabled = true;
        entries.push((
            name.to_string(),
            PluginEntry {
                path: PathBuf::from(filename),
                enabled,
                kind: PluginKind::Process,
                extensions: Vec::new(),
                syntax_file: None,
                events: Vec::new(),
            },
        ));
    }
    for (name, syntax_rel_path, extensions) in BUNDLED_SYNTAX_PLUGIN_ENTRIES {
        let extensions: Vec<String> = extensions.iter().map(|s| s.to_string()).collect();
        entries.push((
            name.to_string(),
            PluginEntry {
                path: PathBuf::from(syntax_rel_path),
                enabled: true,
                kind: PluginKind::Syntax,
                extensions,
                syntax_file: Some(PathBuf::from(syntax_rel_path)),
                events: Vec::new(),
            },
        ));
    }
    entries
}

/// Default plugin discovery directory.
///
/// - Linux/macOS: `$XDG_CONFIG_HOME/mantis/plugins/` (falls back to
///   `~/.config/mantis/plugins/` when the variable is unset)
/// - Windows:     `%APPDATA%\mantis\plugins\`
pub(crate) fn default_plugin_dir() -> PathBuf {
    dirs_next().unwrap_or_else(|| PathBuf::from("."))
}

fn dirs_next() -> Option<PathBuf> {
    #[cfg(windows)]
    {
        std::env::var_os("APPDATA").map(|p| PathBuf::from(p).join("mantis").join("plugins"))
    }
    #[cfg(not(windows))]
    {
        std::env::var_os("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
            .map(|base| base.join("mantis").join("plugins"))
    }
}

/// List of (user-facing_name, binary_name, embedded_binary_data) for each
